-- ---------------------------------------------------------------------------
-- Cobranca no provedor de pagamento e clientes (pagadores) no provedor.
-- ---------------------------------------------------------------------------
-- A cobranca so vai para o Asaas quando alguem clica em Pagar. SITUACAO_PROVEDOR
-- acompanha isso (NAO_EMITIDA -> EMITINDO -> EMITIDA | FALHA_EMISSAO); STATUS
-- (PENDENTE/EM_ATRASO/PAGA/CANCELADA) continua como estava.
ALTER TABLE COBRANCA ADD COLUMN SITUACAO_PROVEDOR VARCHAR(15) NOT NULL DEFAULT 'NAO_EMITIDA'
    CHECK (SITUACAO_PROVEDOR IN ('NAO_EMITIDA', 'EMITINDO', 'EMITIDA', 'FALHA_EMISSAO'));
ALTER TABLE COBRANCA ADD COLUMN FORMA_PAGAMENTO VARCHAR(6) CHECK (FORMA_PAGAMENTO IN ('PIX', 'BOLETO'));
ALTER TABLE COBRANCA ADD COLUMN ID_COBRANCA_EXTERNA VARCHAR(64) UNIQUE;
ALTER TABLE COBRANCA ADD COLUMN EMISSAO_INICIADA_EM TIMESTAMPTZ;
ALTER TABLE COBRANCA ADD COLUMN EMITIDA_EM TIMESTAMPTZ;
ALTER TABLE COBRANCA ADD COLUMN ULTIMO_ERRO_PROVEDOR VARCHAR(500);
ALTER TABLE COBRANCA ADD COLUMN VERSAO BIGINT NOT NULL DEFAULT 0;
-- Alvo da FK composta de PAGAMENTO_COBRANCA (V27): o pagamento e da mesma escola da cobranca.
ALTER TABLE COBRANCA ADD CONSTRAINT uk_cobranca_id_escola UNIQUE (ID_COBRANCA, ESCOLA_ID);
ALTER TABLE COBRANCA ADD CONSTRAINT ck_cobranca_emitida
    CHECK (SITUACAO_PROVEDOR <> 'EMITIDA' OR (ID_COBRANCA_EXTERNA IS NOT NULL AND FORMA_PAGAMENTO IS NOT NULL));
-- A reconciliacao procura emissoes que ficaram sem resposta.
CREATE INDEX cobranca_emitindo_idx ON COBRANCA (EMISSAO_INICIADA_EM) WHERE SITUACAO_PROVEDOR = 'EMITINDO';

-- Cliente (pagador) dentro de cada conta Asaas. Um por pessoa na conta filha da
-- escola (Fluxo B) e um por escola na conta-pai (Fluxo A).
CREATE TABLE CLIENTE_PROVEDOR (
    ID_CLIENTE_PROVEDOR  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ESCOLA_ID            UUID NOT NULL REFERENCES ESCOLA (ID_ESCOLA),
    CONTA                VARCHAR(5) NOT NULL CHECK (CONTA IN ('FILHA', 'PAI')),
    REFERENCIA_EXTERNA   VARCHAR(60) NOT NULL,          -- EDK-PES-<id> ou EDK-ESC-<id>
    ID_CLIENTE_EXTERNO   VARCHAR(64) NOT NULL,
    CRIADO_EM            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cliente_provedor UNIQUE (ESCOLA_ID, CONTA, REFERENCIA_EXTERNA)
);
